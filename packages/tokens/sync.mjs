// Single source of design tokens: writes CSS variables for web and a TS module for web and mobile.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
const t = JSON.parse(readFileSync(new URL('./src/tokens.json', import.meta.url)));
const kebab = (s) => s.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase());
let css = '/* Generated by packages/tokens/sync.mjs. Do not edit. */\n:root {\n';
for (const [k, v] of Object.entries(t.color)) css += `  --${kebab(k)}: ${v};\n`;
for (const [k, v] of Object.entries(t.space)) css += `  --space-${k}: ${v}px;\n`;
for (const [k, v] of Object.entries(t.radius)) css += `  --radius-${k}: ${v}px;\n`;
css += `  --font-sans: ${t.font.sans};\n  --font-serif: ${t.font.serif};\n}\n`;
const ts = `// Generated by packages/tokens/sync.mjs. Do not edit.\nexport const tokens = ${JSON.stringify(t, null, 2)} as const;\n`;
const out = (p, c) => { mkdirSync(new URL(p, import.meta.url).pathname.replace(/[^/]+$/, ''), { recursive: true }); writeFileSync(new URL(p, import.meta.url), c); };
out('../../apps/web/src/design/tokens.css', css);
out('../../apps/web/src/design/tokens.ts', ts);
out('../../apps/mobile/src/design/tokens.ts', ts);
console.log('tokens synced');
